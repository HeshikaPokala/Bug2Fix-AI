"""Repeatable eval harness for the demo bug set.

Runs every bug_report/log pair in demo/bug_reports + demo/logs through the
pipeline twice -- once with --no-llm (the deterministic fallback alone) and
once with Ollama enabled -- and writes a summary table + JSON to
demo/results/. This replaces one-off manual runs with something you can
re-run after any change and get a real, comparable number.

Usage:
    python3 scripts/run_eval_suite.py                 # both modes
    python3 scripts/run_eval_suite.py --skip-llm       # deterministic only (fast, no Ollama needed)
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from app.orchestrator.graph import run_workflow  # noqa: E402

BUG_ID_PATTERN = re.compile(r"^bug(\d+)_")


def discover_bugs() -> list[tuple[str, Path, Path]]:
    bug_reports_dir = PROJECT_ROOT / "demo" / "bug_reports"
    logs_dir = PROJECT_ROOT / "demo" / "logs"
    bugs = []
    for report_path in sorted(bug_reports_dir.glob("bug*.md")):
        match = BUG_ID_PATTERN.match(report_path.stem)
        if not match:
            continue
        bug_id = f"bug{match.group(1)}"
        candidates = list(logs_dir.glob(f"{bug_id}_*.log"))
        if not candidates:
            print(f"warning: no log file found for {report_path.name}, skipping", file=sys.stderr)
            continue
        bugs.append((bug_id, report_path, candidates[0]))
    return bugs


def run_one(bug_report: Path, logs: Path, use_llm: bool, tmp_root: Path) -> dict:
    out_dir = tmp_root / f"{bug_report.stem}_{'llm' if use_llm else 'nollm'}"
    result = run_workflow(
        bug_report_path=bug_report,
        logs_path=logs,
        repo_root=PROJECT_ROOT / "mini_repo",
        output_dir=out_dir,
        workspace_root=PROJECT_ROOT,
        use_llm=use_llm,
        traces_dir=tmp_root / "traces",
    )
    report = json.loads(Path(result["final_report_path"]).read_text(encoding="utf-8"))
    repro = report["repro"]["result"]
    return {
        "function": report["likely_failure_surface"].get("function", "unknown"),
        "module": report["likely_failure_surface"].get("module", "unknown"),
        "error_type": report["likely_failure_surface"].get("error_type", "unknown"),
        "repro_confirmed": bool(repro.get("failed_consistently")),
        "llm_assisted": bool(repro.get("llm_assisted")),
        "llm_attempts": repro.get("llm_attempts", 0),
        "confidence": report.get("confidence"),
        "root_cause_source": report.get("root_cause_hypothesis", {}).get("source"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-llm", action="store_true", help="Only run the deterministic (--no-llm) pass.")
    args = parser.parse_args()

    bugs = discover_bugs()
    if not bugs:
        print("No bugs found under demo/bug_reports + demo/logs.", file=sys.stderr)
        sys.exit(1)

    print(f"Discovered {len(bugs)} bug scenario(s): {', '.join(b[0] for b in bugs)}\n")

    with tempfile.TemporaryDirectory(prefix="bug2fix_eval_") as tmp:
        tmp_root = Path(tmp)
        rows = []
        for bug_id, bug_report, logs in bugs:
            print(f"--- {bug_id}: {bug_report.name} ---")
            nollm = run_one(bug_report, logs, use_llm=False, tmp_root=tmp_root)
            print(f"  no-llm : diagnosed {nollm['function']} ({nollm['error_type']}) | repro={nollm['repro_confirmed']}")
            row = {"bug_id": bug_id, "diagnosis": f"{nollm['function']} / {nollm['error_type']}", "nollm": nollm}
            if not args.skip_llm:
                llm = run_one(bug_report, logs, use_llm=True, tmp_root=tmp_root)
                print(
                    f"  llm    : repro={llm['repro_confirmed']} llm_assisted={llm['llm_assisted']} "
                    f"attempts={llm['llm_attempts']} confidence={llm['confidence']}"
                )
                row["llm"] = llm
            rows.append(row)
            print()

    results_dir = PROJECT_ROOT / "demo" / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "eval_summary.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")

    lines = ["# Eval suite summary", "", f"{len(rows)} bug scenarios, auto-generated by `scripts/run_eval_suite.py`.", ""]
    if args.skip_llm:
        lines += ["| Bug | Diagnosis | Repro (no-llm) |", "|---|---|---|"]
        for row in rows:
            lines.append(f"| {row['bug_id']} | {row['diagnosis']} | {row['nollm']['repro_confirmed']} |")
    else:
        lines += [
            "| Bug | Diagnosis | Repro (no-llm) | Repro (llm) | LLM-assisted | Attempts | Confidence |",
            "|---|---|---|---|---|---|---|",
        ]
        for row in rows:
            llm = row["llm"]
            lines.append(
                f"| {row['bug_id']} | {row['diagnosis']} | {row['nollm']['repro_confirmed']} | "
                f"{llm['repro_confirmed']} | {llm['llm_assisted']} | {llm['llm_attempts']} | {llm['confidence']} |"
            )
        nollm_success = sum(1 for r in rows if r["nollm"]["repro_confirmed"])
        llm_success = sum(1 for r in rows if r["llm"]["repro_confirmed"])
        lines += [
            "",
            f"**Diagnosis correct: {len(rows)}/{len(rows)}** (log parsing, LLM-independent).",
            f"**Repro confirmed, no-llm: {nollm_success}/{len(rows)}**.",
            f"**Repro confirmed, with Ollama: {llm_success}/{len(rows)}**.",
        ]
    (results_dir / "eval_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Wrote {results_dir / 'eval_summary.json'}")
    print(f"Wrote {results_dir / 'eval_summary.md'}")


if __name__ == "__main__":
    main()
